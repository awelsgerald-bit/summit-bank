import { useEffect, useState } from 'react';
import { ArrowLeft, Printer, Share2 } from 'lucide-react';
import { Link, useParams } from 'react-router-dom';
import api from '../api/client';
import { errorMessage, formatDateTime, formatMoney } from '../utils/errors';

const STATUS_LABEL = { approved: 'Successful', pending: 'Pending approval', rejected: 'Rejected' };

function Line({ label, value, mono }) {
  return (
    <div className="flex items-start justify-between gap-4 py-3 text-sm">
      <span className="text-[var(--text-3)]">{label}</span>
      <span className={`text-right break-all ${mono ? 'font-mono' : ''}`}>{value || '—'}</span>
    </div>
  );
}

export default function Receipt() {
  const { id } = useParams();
  const [receipt, setReceipt] = useState(null);
  const [error, setError] = useState('');
  const [note, setNote] = useState('');

  useEffect(() => {
    let cancelled = false;
    async function load() {
      try {
        const res = await api.get(`/transactions/${id}/receipt`);
        if (!cancelled) setReceipt(res.data);
      } catch (err) {
        if (!cancelled) setError(errorMessage(err, 'Could not load this receipt.'));
      }
    }
    load();
    return () => {
      cancelled = true;
    };
  }, [id]);

  async function share() {
    if (!receipt) return;
    const text = [
      'Summit Bank receipt',
      `Reference: ${receipt.reference}`,
      `${receipt.direction === 'credit' ? 'Received' : 'Paid'}: ${formatMoney(receipt.amount, receipt.currency)}`,
      `Status: ${STATUS_LABEL[receipt.status] || receipt.status}`,
      `Date: ${formatDateTime(receipt.timestamp)}`,
    ].join('\n');
    try {
      if (navigator.share) {
        await navigator.share({ title: `Receipt ${receipt.reference}`, text });
      } else {
        await navigator.clipboard.writeText(text);
        setNote('Receipt details copied. Paste them into any chat.');
      }
    } catch {
      // the person closed the share sheet; nothing to do
    }
  }

  if (error) {
    return (
      <div className="max-w-md mx-auto space-y-4">
        <div className="text-sm text-[var(--danger)] bg-[rgba(251,113,133,0.1)] border border-[rgba(251,113,133,0.25)] rounded-xl px-4 py-3">
          {error}
        </div>
        <Link to="/history" className="text-sm text-[var(--pink-accent)]">Back to activity</Link>
      </div>
    );
  }
  if (!receipt) return <p className="text-sm text-[var(--text-3)]">Loading receipt...</p>;

  const credit = receipt.direction === 'credit';
  const label = receipt.type === 'transfer' ? (credit ? 'Transfer received' : 'Transfer sent') : receipt.type;

  return (
    <div className="max-w-md mx-auto space-y-5">
      <Link to="/history" className="no-print inline-flex items-center gap-1 text-sm text-[var(--text-2)]">
        <ArrowLeft size={15} /> Back
      </Link>

      <div className="print-area glass rounded-3xl p-6">
        <div className="text-center pb-5 border-b border-white/10">
          <p className="font-display text-sm text-[var(--text-3)]">Summit Bank · Transaction receipt</p>
          <p className="font-display text-3xl font-semibold mt-3">{formatMoney(receipt.amount, receipt.currency)}</p>
          <p className="text-sm mt-1 capitalize">{label}</p>
          <p
            className="inline-block text-xs mt-3 px-3 py-1 rounded-full"
            style={{
              background: receipt.status === 'approved' ? 'rgba(52,211,153,0.15)' : 'rgba(251,191,36,0.15)',
              color: receipt.status === 'approved' ? '#34D399' : receipt.status === 'rejected' ? '#FB7185' : '#FBBF24',
            }}
          >
            {STATUS_LABEL[receipt.status] || receipt.status}
          </p>
        </div>

        <div className="divide-y divide-white/5">
          <Line label="Reference" value={receipt.reference} mono />
          <Line label="Date" value={`${formatDateTime(receipt.timestamp)} (WAT)`} />
          <Line label={credit ? 'Credited to' : 'Debited from'} value={receipt.account_holder.name} />
          <Line label="Account number" value={receipt.account_holder.account_number} mono />
          {receipt.other_party && (
            <>
              <Line label={credit ? 'Sent by' : 'Sent to'} value={receipt.other_party.name} />
              <Line label={credit ? 'Sender account' : 'Recipient account'} value={receipt.other_party.account_number} mono />
            </>
          )}
          <Line label="Description" value={receipt.description} />
        </div>
        <p className="text-[11px] text-[var(--text-3)] text-center pt-4">
          This receipt was generated by Summit Bank. Keep the reference for any enquiry.
        </p>
      </div>

      <div className="no-print flex gap-3">
        <button
          onClick={() => window.print()}
          className="btn-primary flex-1 rounded-full py-3 text-sm font-medium flex items-center justify-center gap-2"
        >
          <Printer size={16} /> Download PDF
        </button>
        <button
          onClick={share}
          className="flex-1 rounded-full py-3 text-sm border border-white/10 text-[var(--text-1)] flex items-center justify-center gap-2"
        >
          <Share2 size={16} /> Share
        </button>
      </div>
      {note && <p className="no-print text-xs text-[var(--success)] text-center">{note}</p>}
      <p className="no-print text-xs text-[var(--text-3)] text-center">
        For a PDF, choose "Save as PDF" as the printer in the window that opens.
      </p>
    </div>
  );
}
